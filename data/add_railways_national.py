def densify(points, step=0.02):
    out = [points[0]]
    for a, b in zip(points, points[1:]):
        dd = ((b[0]-a[0])**2 + (b[1]-a[1])**2) ** 0.5
        n = max(1, int(dd/step))
        for i in range(1, n + 1):
            t = i / n
            out.append([round(a[0] + (b[0]-a[0])*t, 6), round(a[1] + (b[1]-a[1])*t, 6)])
    return out

