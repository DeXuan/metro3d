MARGIN = 0.10
added = {}
for c in d['cities']:
    if c.get('kind') == 'bridges': continue
    if c.get('railways'): continue          # 已有（洛阳）跳过
    lines = c.get('lines', [])
    if not lines: continue
    lgs = [s['lng'] for l in lines for s in l['stations']]
    lts = [s['lat'] for l in lines for s in l['stations']]
    bbox = (min(lgs)-MARGIN, max(lgs)+MARGIN, min(lts)-MARGIN, max(lts)+MARGIN)
    rows = []
    for cor in CORRIDORS:
        if c['id'] in cor.get('skip', []): continue
        dense = densify(cor['points'], 0.02)
        flags = [bbox[0] <= x <= bbox[1] and bbox[2] <= y <= bbox[3] for x, y in dense]
        best = (0, 0, 0)
        i = 0
        while i < len(flags):
            if flags[i]:
                j = i
                while j < len(flags) and flags[j]: j += 1
                if j - i > best[0]: best = (j - i, i, j)
                i = j
            else: i += 1
        if best[0] == 0: continue
        s0, e0 = best[1], best[2]
        seg = dense[max(0, s0-1):min(len(dense), e0+1)]
        span = max(x[0] for x in seg) - min(x[0] for x in seg) + max(x[1] for x in seg) - min(x[1] for x in seg)
        sts = {k: v for k, v in cor['stations'].items() if bbox[0] <= v[0] <= bbox[1] and bbox[2] <= v[1] <= bbox[3]}
        if len(seg) < 5 and not sts: continue
        if span < 0.18 and not sts: continue
        rows.append({
          'name': cor['name'], 'desc': cor['desc'], 'type': 'hsr',
          'color': '#E8ECF2', 'year': cor['year'],
          'points': seg, 'stations': [{'name': k, 'lng': v[0], 'lat': v[1]} for k, v in sts.items()],
        })
    if rows:
        c['railways'] = rows
        added[c['name']] = len(rows)

