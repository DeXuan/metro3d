def build_line(key, stations, color, name, line_from, line_to, length, to_end='', branch_of=None):
    sts = []
    elevcfg = ELEV.get(key)
    e_set = elevcfg.get('e', set()) if elevcfg else set()
    g_set = elevcfg.get('g', set()) if elevcfg else set()
    for c in stations:
        nm = c['name']
        if nm in g_set:
            sts.append({'name': nm, 'lng': c['lng'], 'lat': c['lat'],
                        'type': 'ground', 'height': 0})
        elif nm in e_set:
            base_h = 13 if key in ('3', '11', '16') else 9
            sts.append({'name': nm, 'lng': c['lng'], 'lat': c['lat'],
                        'type': 'elevated', 'height': round(jitter(nm, base_h, 3), 1)})
        else:
            depth = KD.get(nm, jitter(nm, BASE[key], 2.5))
            sts.append({'name': nm, 'lng': c['lng'], 'lat': c['lat'],
                        'type': 'underground', 'depth': depth})
        if nm in TRANSFER:
            sts[-1]['transfer'] = TRANSFER[nm]
        if c.get('approx'):
            sts[-1]['note'] = (sts[-1].get('note', '') + '；' if sts[-1].get('note') else '') + c['approx']
    out = {'id': 'sh-' + key, 'name': name, 'color': color,
           'from': line_from, 'to': line_to, 'lengthKm': length,
           'stations': sts}
    if branch_of:
        out['branchOf'] = branch_of
    return out

